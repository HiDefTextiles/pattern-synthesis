"""Render one knitted piece (a window of the endless banner) with the full
version-1 output set: preview, grid, chart, provenance and validation.

Settings come from banner.yml (see DECISIONS.md). Outputs are in machine
orientation: one line per knitted row, one column per needle.

Usage (from the repo root):
    python3 python/make_banner.py --seed 1 --first 0 --out out/banner
"""
from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from banner import CORPUS_DIR, PALETTE2, Banner, MotifPolicy, source_of
from fillers import FILLERS
from sjonabok import Corpus, Pattern
from validate import Settings, validate

GENERATOR_VERSION = "0.1.0"
CREATOR = "Helga Ingimundardóttir, Háskóli Íslands"
DIGITISED_BY = "HiDef Textiles"
INSTITUTIONS = ["Heimilisiðnaðarfélag Íslands", "Listaháskóli Íslands", "Þjóðminjasafn Íslands"]


class BannerJob:
    """One window of the endless banner, built from the settings file."""

    def __init__(self, settings: Settings, seed: int, first: int, filler: str = "wfc"):
        self.s, self.seed, self.first, self.filler = settings, seed, first, filler
        lay = settings.layout
        self.corpus = Corpus(CORPUS_DIR)
        pool = [m for m in self.corpus.motifs(19, 45) if m.shape[0] % 2]
        if lay["source_scope"] == "single":
            groups = [lay["source_group"]]
        else:
            groups = lay.get("allowed_source_groups") or sorted({source_of(m.name) for m in pool})
        self.pool = [m for m in pool if source_of(m.name) in groups]
        if len(self.pool) < 2:
            raise ValueError(f"source groups {groups} have fewer than 2 usable motifs")
        kind = "mix" if lay["source_scope"] == "single" else lay.get("mixed_mode", "manuscripts")
        self.banner = Banner("v1", seed, MotifPolicy(kind, self.pool),
                             self.corpus.band_tile(lay["band"]), corpus=self.corpus,
                             needles=lay["width"], gap=lay.get("gap", 14),
                             filler=FILLERS[filler]())

    def render(self) -> tuple[np.ndarray, np.ndarray, int]:
        """Machine-orientation chart and generated mask, cropped to window_rows."""
        want, last = self.s.layout["window_rows"], self.first + 1
        while True:
            chart, gen, _ = self.banner.render(self.first, last)
            if chart.shape[1] >= want:
                return chart[:, :want].T.copy(), gen[:, :want].T.copy(), last
            last += 1

    def meta(self, chart: np.ndarray, gen: np.ndarray, last: int) -> dict:
        labels = self.banner.labels(self.first, last)
        items = []
        for k, name in zip(range(self.first, last + 1), labels):
            base = name[4:].split(">")[0] if name.startswith("new(") else name
            items.append({"slot": k, "source_group": source_of(base), "source_id": base,
                          "role": "derived_motif" if name.startswith("new") else "pinned_motif"})
        stitched = chart > 0
        copied = float((stitched & ~gen).sum() / max(stitched.sum(), 1))
        groups = sorted({i["source_group"] for i in items})
        return {
            "work_id": f"banner-seed{self.seed}-slots{self.first}-{last}",
            "generator_version": GENERATOR_VERSION,
            "commits": {"pattern_synthesis": git_rev("."), "sjonabok": git_rev("data/sjonabok")},
            "seed": self.seed, "window": {"first_slot": self.first, "last_slot": last},
            "filler": self.filler,
            "settings": {"layout": self.s.layout, "colour": self.s.colour,
                         "machine_profile": self.s.machine_profile},
            "creator": CREATOR,
            "provenance": [
                {"step": "original manuscripts", "held_by": "Þjóðminjasafn Íslands "
                 "(natmus453: National Museum of Denmark)"},
                {"step": "compiled into a book", "year": 2009, "by": INSTITUTIONS,
                 "title": "Íslensk sjónabók / Ornaments and Patterns Found in Iceland"},
                {"step": "digitised", "year": 2024, "by": DIGITISED_BY},
                {"step": "new pattern generated by algorithm", "year": 2026, "by": CREATOR},
            ],
            "border_band": self.s.layout["band"],
            "source_manuscripts": [museum_no(g) for g in groups],
            "source_items": items,
            "copy_novelty": {"requested_ratio": self.s.layout["copy_novelty_ratio"],
                             "measured_copied_share_of_stitches": round(copied, 3)},
            "rights": {"source_patterns": "public domain",
                       "generated_output": "CC BY 4.0", "generated_output_url": "https://creativecommons.org/licenses/by/4.0/", "code": "GPL-3.0"},
            "credit": credit(groups),
        }


MUSEUM_NO = {"natmus453": "Natmus 453", "thjmsth_116": "Þjms. Þ. og Þ. Th. 116"}


def museum_no(group: str) -> str:
    """thjms1105 -> 'Þjms. 1105'; natmus453 -> 'Natmus 453'."""
    return MUSEUM_NO.get(group, "Þjms. " + group.removeprefix("thjms"))


def credit(groups: list[str]) -> str:
    return (f"Pattern by {CREATOR.split(',')[0]}, CC BY 4.0, after "
            + ", ".join(museum_no(g) for g in groups) + ".")


def git_rev(path: str) -> str | None:
    try:
        return subprocess.run(["git", "-C", path, "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def grid_png(chart: np.ndarray, path: Path, palette, cell: int = 8, every: int = 10) -> None:
    """Enlarged chart with grid lines and row / needle numbers every `every` cells."""
    rows, cols = chart.shape
    m = 28
    img = Image.new("RGB", (cols * cell + m, rows * cell + m), "white")
    d = ImageDraw.Draw(img)
    rgb = np.array(palette, dtype=np.uint8)[chart]
    img.paste(Image.fromarray(rgb, "RGB").resize((cols * cell, rows * cell), Image.NEAREST), (m, m))
    for x in range(cols + 1):
        d.line([(m + x * cell, m), (m + x * cell, m + rows * cell)],
               fill=(90, 90, 90) if x % every == 0 else (200, 200, 200))
        if x % every == 0 and x < cols:
            d.text((m + x * cell + 1, 4), str(x + 1), fill="black")
    for y in range(rows + 1):
        d.line([(m, m + y * cell), (m + cols * cell, m + y * cell)],
               fill=(90, 90, 90) if y % every == 0 else (200, 200, 200))
        if y % every == 0 and y < rows:
            d.text((2, m + y * cell + 1), str(y + 1), fill="black")
    img.save(path)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--settings", type=Path, default=Path("banner.yml"))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--first", type=int, default=0, help="first motif slot of the window")
    ap.add_argument("--filler", default="wfc", choices=list(FILLERS))
    ap.add_argument("--out", type=Path, default=Path("out/banner"))
    args = ap.parse_args()

    s = Settings.load(args.settings)
    for w in s.check():
        print("warning:", w)
    job = BannerJob(s, args.seed, args.first, args.filler)
    chart, gen, last = job.render()
    args.out.mkdir(parents=True, exist_ok=True)
    o = args.out
    Pattern("banner", chart).save_txt(o / "banner.txt")
    Pattern("banner", chart).save_png(o / "banner.png", PALETTE2, zoom=4)
    grid_png(chart, o / "banner-grid.png", PALETTE2)
    (o / "banner.json").write_text(json.dumps({
        "rows": int(chart.shape[0]), "width": int(chart.shape[1]),
        "orientation": "row = knitted row, column = needle",
        "palette": [list(c) for c in PALETTE2[:2]],
        "cells": ["".join(map(str, r)) for r in chart]}, indent=1))
    meta = job.meta(chart, gen, last)
    (o / "banner.meta.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False))
    rep = validate(chart, s)
    (o / "banner.validation.json").write_text(json.dumps(rep.to_dict(), indent=1))
    print(f"{o}: {chart.shape[0]} rows x {chart.shape[1]} needles, slots {args.first}-{last}, "
          f"copied {meta['copy_novelty']['measured_copied_share_of_stitches']:.0%}, "
          f"longest interior float {rep.floats['max_interior']}, "
          f"{'OK' if rep.ok else 'ERRORS: ' + '; '.join(rep.errors)}")
    for w in rep.warnings:
        print("warning:", w)


if __name__ == "__main__":
    main()
